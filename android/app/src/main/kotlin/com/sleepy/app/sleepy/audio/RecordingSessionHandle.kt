package com.sleepy.app.sleepy.audio

/**
 * Минимальный контракт сессии, которым управляет служба.
 *
 * Интерфейс отделяет жизненный цикл службы от Android и позволяет
 * проверить повторный запуск, остановку и watchdog без устройства.
 */
internal interface RecordingSessionHandle {

    /** Поток захвата ещё жив (в том числе доделывает закрытие файлов). */
    val isActive: Boolean

    /** Запускает сессию; `false` — запуск не удался. */
    fun start(): Boolean

    /** Просит сессию остановиться, не блокируя вызывающий поток. */
    fun stop()
}
